function toProfile(person: SeedPerson): AlumniProfile {
  const fullName = `${person.firstName} ${person.lastName}`;
  return {
    interests: [],
    activities: [],
    clubs: [],
    helpOffers: [],
    visibility: "alumni",
    status: "verified",
    approvedBy: [],
    ...person,
    fullName,
    searchName: fullName.toLowerCase(),
    fieldVisibility: { ...DEFAULT_FIELD_VISIBILITY },
    createdAt: agoIso(400),
    updatedAt: agoIso(30),
  };
}

